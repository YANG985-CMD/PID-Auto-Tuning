function metric = ccmp_metrics(t)
c=ccmp_config(); elapsed=t.time_s(end)-t.time_s(1); err=t.reference_rpm-t.speed_rpm;
used=t.time_s>=.5; dt=diff(t.time_s(used)); e=err(used);
late=t.time_s>=2; lateTime=t.time_s(late); lateError=err(late);
gains=t{:,{'Kp','Ki'}}; changed=[true;any(diff(gains,1,1)~=0,2)];
delta=[gains(1,:)-c.baseline';diff(gains(changed,:),1,1)];
metric=struct('rmse_rpm',sqrt(trapz(t.time_s,err.^2)/elapsed), ...
    'rmse_after_0p5s_rpm',sqrt(sum(.5*(e(1:end-1).^2+e(2:end).^2).*dt)/sum(dt)), ...
    'rmse_after_2s_rpm',sqrt(trapz(lateTime,lateError.^2)/(lateTime(end)-lateTime(1))), ...
    'peak_phase_current_A',max(abs(t{:,{'ia_A','ib_A','ic_A'}}),[],'all'), ...
    'peak_abs_speed_rpm',max(abs(t.speed_rpm)), ...
    'iq_command_saturation_fraction',trapz(t.time_s,double(abs(t.iq_ref_A)>=3-1e-6))/elapsed, ...
    'gain_changes',sum(changed)-1+any(delta(1,:)~=0),'max_Kp_step',max([0;abs(delta(:,1))]), ...
    'max_Ki_step',max([0;abs(delta(:,2))]),'sample_count',height(t), ...
    'gain_bounds_passed',all(gains>=c.lower'-1e-10 & gains<=c.upper'+1e-10,'all'), ...
    'gain_step_passed',all(abs(delta)<=c.step'+1e-10,'all'));
assert(metric.gain_bounds_passed && metric.gain_step_passed,'Comparison:Gains','Gain guard violation');
end
