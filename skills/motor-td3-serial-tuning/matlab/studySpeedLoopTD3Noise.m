function report=studySpeedLoopTD3Noise(dataset,outputDir)
% Prespecified 2x2 native TD3 study; no device or counterfactual plant metrics.
arguments
    dataset (1,1) string
    outputDir (1,1) string
end
if ~isfolder(outputDir),mkdir(outputDir);end
configs=[struct(name="default-noise-bc2p5",std=sqrt(.2),clip=.5,bc=2.5), ...
    struct(name="small-noise-bc2p5",std=.05,clip=.1,bc=2.5), ...
    struct(name="default-noise-bc0p25",std=sqrt(.2),clip=.5,bc=.25), ...
    struct(name="small-noise-bc0p25",std=.05,clip=.1,bc=.25)];
seeds=[7;17;27];
replay=validateSpeedLoopResponseReplay(dataset);
report=struct(schema_version=1,source="real_motor_fixed_replay_noise_ablation", ...
    hardware_accessed=false,configs=configs,seeds=seeds,training_steps_per_seed=80, ...
    dataset_sha256=string(replay.summary.dataset_sha256), ...
    window_profile=string(replay.summary.window_profile), ...
    exploratory_only=replay.summary.exploratory_only, ...
    training_experiences=numel(replay.train),validation_experiences=numel(replay.validation), ...
    validation_run_indices=replay.summary.validation_run_indices, ...
    action_mask=[1 1],td3_training_performed=false,total_gradient_steps=0, ...
    performance_claim_allowed=false,deployment_allowed=false,ordinary_live_admission=false, ...
    thermal_gate_modified=false,reports=[]);
f=fopen(fullfile(outputDir,'study-contract.json'),'wb');assert(f>=0);
fwrite(f,unicode2native(jsonencode(report,PrettyPrint=true),'UTF-8'));fclose(f);
outputs=cell(numel(configs),1);comparison=table;
for k=1:numel(configs)
    c=configs(k);
    r=trainSpeedLoopResponseTD3(dataset,fullfile(outputDir,c.name),seeds, ...
        BehaviorCloningWeight=c.bc,TargetNoiseStandardDeviation=c.std*[1;1], ...
        TargetNoiseClip=c.clip);
    outputs{k}=r;
    for j=1:numel(r.seed_reports)
        s=r.seed_reports(j);m=s.validation_after;
        comparison=[comparison;table(c.name,s.seed,c.std,c.clip,c.bc, ...
            s.training_steps_total,m.action_mean(1),m.action_mean(2), ...
            m.behavior_action_mse(1),m.behavior_action_mse(2), ...
            m.critic_disagreement_mean,m.online_bellman_residual_rmse(1), ...
            m.online_bellman_residual_rmse(2),s.actor_weight_change_l2, ...
            string(s.checkpoint_sha256),false, ...
            VariableNames={'config','seed','target_noise_std','target_noise_clip','bc_weight', ...
            'training_steps','kp_action_mean','ki_action_mean','kp_behavior_mse','ki_behavior_mse', ...
            'critic_disagreement','critic1_residual_rmse','critic2_residual_rmse', ...
            'actor_weight_change_l2','checkpoint_sha256','physical_performance_verified'})]; %#ok<AGROW>
    end
end
report.reports=[outputs{:}];
report.td3_training_performed=all([report.reports.td3_training_performed]);
if report.td3_training_performed
    report.total_gradient_steps=sum([report.reports.total_gradient_steps]);
    writetable(comparison,fullfile(outputDir,'ablation.csv'));
end
f=fopen(fullfile(outputDir,'study-summary.json'),'wb');assert(f>=0);
fwrite(f,unicode2native(jsonencode(report,PrettyPrint=true),'UTF-8'));fclose(f);
end
