function report=runMotorFullIntervalStudy(source,output)
arguments
    source (1,1) string
    output (1,1) string
end
assert(jsondecode(fileread(fullfile(output,'profile-tests/profile-test-summary.json'))).passed);
contract=struct(source_replay_sha256=motorFileSHA256(fullfile(source,'replay/summary.json')), ...
    reward_audit_sha256=motorFileSHA256(fullfile(output,'reward-audit/summary.json')), ...
    old_reward_checkpoints_retained=true,learning_reward_profile="full-decision-observed-latency-v1", ...
    critic_learning_rate=1e-5,critic_weight_decay=.01,critic_iterations_per_candidate=600, ...
    actor_current_gain_observed=true,action_mask=[1 0],Ki_fixed=.00144,seeds=[7 17 27], ...
    reward_definition_changed_for_learning=true,primary_physical_performance_metric_unchanged=true, ...
    source_states_actions_and_boot_split_unchanged=true,hardware_accessed=false,actor_applied=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(output,'full-interval-study-contract.json'),contract);studies=struct([]);
for observation=["original","causal"]
    input=fullfile(output,"full-"+observation+"-input.mat");folder=fullfile(output,"train-"+observation+"-full");
    r=trainMotorFullHallTD3(input,fullfile(source,'replay'),folder,600, ...
        Sampling="balanced-actual-actions",RewardModes="complete-Hall",Initialization="near-baseline", ...
        ActorGainFeature="observed",RequireMeasuredSwitches=true,ValueCentering=true, ...
        CriticArchitecture="local-quadratic",CriticWeightDecay=.01,CriticLearningRate=1e-5,TrainingSeedMode="isolated-update-stream");
    diagnoseMotorFullHallCritics(input,string(folder),fullfile(output,"critic-"+observation+"-full.json"));
    diagnoseMotorActorGainDependence(input,folder,fullfile(output,"gain-dependence-"+observation+"-full.json"));
    auditMotorCrossSeedActions(input,folder,fullfile(output,"cross-seed-"+observation+"-full.json"));
    row=struct(observation=observation,critic_updates=r.critic_update_iterations,actor_updates=r.actor_updates, ...
        summary_sha256=motorFileSHA256(fullfile(folder,'training-summary.json')));
    if isempty(studies),studies=row;else,studies(end+1)=row;end %#ok<AGROW>
    write(fullfile(output,'full-interval-study-progress.json'),struct(studies=studies));
end
report=struct(passed=true,contract=contract,studies=studies, ...
    critic_update_iterations=sum([studies.critic_updates]),actor_updates=sum([studies.actor_updates]), ...
    hardware_accessed=false,actor_applied=false,candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(output,'full-interval-study-summary.json'),report);
end
function write(path,value)
assert(~isfile(path) || endsWith(path,'progress.json'));
f=fopen(path,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(value,PrettyPrint=true),'UTF-8'));fclose(f);
end
