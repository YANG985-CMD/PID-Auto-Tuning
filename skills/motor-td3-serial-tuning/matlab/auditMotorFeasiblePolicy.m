function report=auditMotorFeasiblePolicy(input,study,output)
% Frozen network-plus-continuous-clamp diagnostics, never physical admission.
arguments
    input (1,1) string
    study (1,1) string
    output (1,1) string
end
assert(~isfile(output));s=load(input);summary=jsondecode(fileread(fullfile(study,'training-summary.json')));
assert(s.fullHallAudit.passed && motorFileSHA256(input)==string(summary.audited_input_sha256));
assert(string(summary.execution_mode)=="bidirectional-feasible-fraction" && numel(summary.candidates)==3);
rows=s.fullHallValidation;parts=cellfun(@(r)r.observation(:),rows,UniformOutput=false);
x=single(cat(2,parts{:}));actual=cellfun(@(r)r.actual_source_kp,rows)';
results=struct([]);gains=zeros(3,numel(actual));advances=gains;
for k=1:3
    row=summary.candidates(k);path=fullfile(study,"candidate-complete-Hall-seed-"+row.seed+".mat");
    assert(motorFileSHA256(path)==string(row.checkpoint_sha256));p=load(path,'trainingState','contract');
    assert(p.contract.execution_wrapper_required && ~p.contract.runtime_compatible);
    raw=predict(p.trainingState.actor,dlarray(x,'CB'));
    [mapped,map]=motorFeasibleFractionAction(raw,dlarray(x,'CB'),p.contract);
    action=double(extractdata(mapped));gains(k,:)=map.executed_float32_kp;
    baseline=double(motorBidirectionalContinuousActionFromObservation(zeros(2,numel(actual)),x,p.contract));
    assert(all(action(2,:)==0) && all(abs(gains(k,:)-actual)<=.00013556+1e-9));
    q=zeros(2,numel(actual));b=q;nets={p.trainingState.critic1,p.trainingState.critic2};
    for j=1:2
        q(j,:)=predictQ(nets{j},x,single(action));b(j,:)=predictQ(nets{j},x,single(baseline));
    end
    advantage=min(q,[],1)-min(b,[],1);advances(k,:)=advantage;
    value=struct(seed=row.seed,checkpoint_sha256=string(row.checkpoint_sha256), ...
        raw_suggestion_range=row.validation_requested_normalized_Kp_range, ...
        executed_float32_Kp_range=[min(gains(k,:)) max(gains(k,:))], ...
        executed_distinct_float32_Kp_count=numel(unique(gains(k,:))), ...
        mean_relative_Kp_change_percent=100*mean(gains(k,:)/double(single(.003389))-1), ...
        exact_execution_bounds_and_Ki_passed=true, ...
        mean_predicted_executed_advantage_over_reachable_baseline_move=mean(advantage), ...
        positive_predicted_advantage_fraction=mean(advantage>0), ...
        mean_executed_twin_disagreement=mean(abs(q(1,:)-q(2,:))), ...
        target_noise_executed_changes=row.target_smoothing_executed_action_changes, ...
        target_action_samples=row.target_action_samples, ...
        no_nearest_grid_quantization=true,no_straight_through_surrogate=true, ...
        independent_frozen_actor_response_verified=false,candidate_admission=false, ...
        deployment_allowed=false,performance_claim_allowed=false);
    if isempty(results),results=value;else,results(end+1)=value;end %#ok<AGROW>
end
spread=max(gains,[],1)-min(gains,[],1);
report=struct(passed=true,results=results,validation_states=numel(actual), ...
    mean_cross_seed_executed_Kp_spread=mean(spread),maximum_cross_seed_executed_Kp_spread=max(spread), ...
    fraction_states_positive_advantage_for_all_seeds=mean(all(advances>0,1)), ...
    all_policies_constant_after_execution=all([results.executed_distinct_float32_Kp_count]==1), ...
    total_target_noise_executed_changes=sum([results.target_noise_executed_changes]), ...
    total_target_action_samples=sum([results.target_action_samples]), ...
    primary_physical_speed_RMSE_improvement_percent=NaN, ...
    Q_contrast_is_one_step_action_under_the_trained_future_policy=true, ...
    Q_contrast_is_not_baseline_controller_performance=true, ...
    surrogate_derivative_used=false,method="TD3+BC with continuous magnitude/rate clipping", ...
    counterfactual_Q_is_not_measured_motor_performance=true,hardware_accessed=false,actor_applied=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
f=fopen(output,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(report,PrettyPrint=true),'UTF-8'));fclose(f);disp(jsonencode(report));
end
function q=predictQ(net,x,a)
q=double(extractdata(predict(net,dlarray(x,'CB'),dlarray(a,'CB'))));
end
