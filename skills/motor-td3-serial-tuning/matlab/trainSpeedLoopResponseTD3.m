function report=trainSpeedLoopResponseTD3(dataset,outputDir,seeds,options)
% Train only an experimental candidate; grouped-decision gamma is explicit.
arguments
    dataset (1,1) string
    outputDir (1,1) string
    seeds (:,1) double = [7;17;27]
    options.BehaviorCloningWeight (1,1) double {mustBePositive,mustBeFinite} = 2.5
    options.TargetNoiseStandardDeviation (2,1) double = sqrt(.2)*ones(2,1)
    options.TargetNoiseClip (1,1) double = .5
    options.Epochs (1,1) double {mustBePositive,mustBeInteger} = 2
    options.StepsPerEpoch (1,1) double {mustBePositive,mustBeInteger} = 40
end
replay=validateSpeedLoopResponseReplay(dataset,[1;1]);
if ~isfolder(outputDir), mkdir(outputDir); end
s=replay.summary;
report=struct(schema_version=2,source="real_motor",hardware_accessed=false, ...
    mode="experimental-held-gain-response",window_profile=string(s.window_profile), ...
    exploratory_only=s.exploratory_only,action_mask=[1 1], ...
    physical_trials=s.source_sessions,replay_experiences=s.response_windows, ...
    training_experiences=numel(replay.train),validation_experiences=numel(replay.validation), ...
    replay_warmup_required=128,training_ready=replay.training_ready, ...
    training_action_coverage=replay.training_action_coverage, ...
    remaining_training_windows=replay.remaining_training_windows, ...
    validation_run_indices=s.validation_run_indices, ...
    dataset_sha256=string(s.dataset_sha256), ...
    discount_contract=string(s.discount_contract), ...
    discount_factor=.99,behavior_cloning_weight=options.BehaviorCloningWeight, ...
    target_noise_standard_deviation=options.TargetNoiseStandardDeviation', ...
    target_noise_clip=options.TargetNoiseClip,epochs=options.Epochs, ...
    steps_per_epoch=options.StepsPerEpoch,algorithm="TD3-with-behavior-cloning", ...
    ki_exploration_performed=replay.training_action_coverage.positive(2)>0 && ...
        replay.training_action_coverage.negative(2)>0, ...
    temperature_c=NaN,current_conversion_independently_calibrated=false, ...
    td3_training_performed=false,seed_reports=[],candidate_files=strings(0,1), ...
    deployment_allowed=false,ordinary_live_admission=false,thermal_gate_modified=false, ...
    performance_claim_allowed=false,offline_performance_verified=false);
if ~replay.training_ready
    report.reason="Insufficient held-response replay; no agent or gradient updates created";
    writeReport(outputDir,report); return
end
seedReports=cell(numel(seeds),1);
files=strings(numel(seeds),1);
for k=1:numel(seeds)
    agent=createMotorTD3(seeds(k),[1;1],options.BehaviorCloningWeight, ...
        TargetNoiseStandardDeviation=options.TargetNoiseStandardDeviation, ...
        TargetNoiseClip=options.TargetNoiseClip);
    initialActor=getModel(getActor(agent)); critics=getCritic(agent);
    initialCritics={getModel(critics(1)),getModel(critics(2))};
    for j=1:numel(replay.train)
        r=replay.train{j};
        e=struct('Observation',{{single(r.observation(:))}}, ...
            'Action',{{single(r.action_normalized(:))}},'Reward',double(r.reward), ...
            'NextObservation',{{single(r.next_observation(:))}},'IsDone',0);
        validateExperience(agent.ExperienceBuffer,e); append(agent.ExperienceBuffer,e);
    end
    before=diagnoseMotorTD3Policy(agent,replay.validation);
    trainingStats=trainFromData(agent,rlTrainingFromDataOptions('MaxEpochs',options.Epochs, ...
        'NumStepsPerEpoch',options.StepsPerEpoch,'Plots','none','Verbose',false,'SaveAgentCriteria','none'));
    after=diagnoseMotorTD3Policy(agent,replay.validation);
    models=getCritic(agent); actor=getModel(getActor(agent));
    predictions=after.predictions{:,{'actor_kp_action','actor_ki_action'}};
    bounds=all(abs(predictions(:))<=1+1e-6);
    states=cell2mat(cellfun(@(r)r.state(:),replay.validation,UniformOutput=false)');
    proposed=states(8:9,:)+predictions'.*[.00027112;.000144];
    numericGainBounds=all(proposed(1,:)>=.0013556 & proposed(1,:)<=.0054224 & ...
        proposed(2,:)>=.00072 & proposed(2,:)<=.00216) && bounds;
    reportSeed=struct(seed=seeds(k),training_steps_total=double(trainingStats.TotalSteps(end)), ...
        actor_weight_change_l2=modelDelta(initialActor,actor), ...
        critic_weight_change_l2=[modelDelta(initialCritics{1},getModel(models(1))), ...
            modelDelta(initialCritics{2},getModel(models(2)))], ...
        validation_before=before.metrics,validation_after=after.metrics, ...
        epoch_q_value=double(trainingStats.QValue),action_bounds_passed=bounds, ...
        gain_bounds_passed=numericGainBounds,ki_masked=false, ...
        deployment_allowed=false,performance_claim_allowed=false);
    file=fullfile(outputDir,"response-candidate-seed-"+seeds(k)+".mat");
    save(file,'agent','trainingStats','reportSeed');
    reportSeed.checkpoint_sha256=motorFileSHA256(file);
    exportMotorTD3DiagnosticJSON(file,fullfile(outputDir,"networks-seed-"+seeds(k)+".json"));
    writetable(after.predictions,fullfile(outputDir,"validation-seed-"+seeds(k)+".csv"));
    seedReports{k}=reportSeed; files(k)=file;
end
report.seed_reports=[seedReports{:}]; report.candidate_files=files;
report.seed_kp_action_means=cellfun(@(r)r.validation_after.action_mean(1),seedReports);
report.seed_kp_action_direction_consistent=all(report.seed_kp_action_means>=0) || ...
    all(report.seed_kp_action_means<=0);
report.td3_training_performed=true;
report.total_gradient_steps=sum(cellfun(@(r)r.training_steps_total,seedReports));
report.reason="Experimental held-response fitting; no physical performance admission";
writeReport(outputDir,report);
end

function value=modelDelta(a,b)
value=0;
for k=1:height(a.Learnables)
    value=value+sum(double(extractdata(b.Learnables.Value{k}-a.Learnables.Value{k})).^2,'all');
end
value=sqrt(value);
end

function writeReport(folder,report)
fid=fopen(fullfile(folder,'response-training-summary.json'),'wb'); assert(fid>=0);
closer=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,unicode2native(jsonencode(report,PrettyPrint=true),'UTF-8'),'uint8');
end
