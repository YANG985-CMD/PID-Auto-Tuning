function report=auditMotorExecutedPolicy(input,study,output)
% Evaluate the complete frozen Actor-plus-map policy in its own coordinates.
arguments
    input (1,1) string
    study (1,1) string
    output (1,1) string
end
assert(~isfile(output));s=load(input);summary=jsondecode(fileread(fullfile(study,'training-summary.json')));
assert(s.fullHallAudit.passed && motorFileSHA256(input)==string(summary.audited_input_sha256));
assert(string(summary.execution_mode)=="upper8-exact-grid-straight-through");
spec=motorStreamGainSpec("upper8-fullhall");rows=s.fullHallValidation;
parts=cellfun(@(r)r.observation(:),rows,UniformOutput=false);x=single(cat(2,parts{:}));
actual=cellfun(@(r)r.actual_source_kp,rows)';results=struct([]);policies=zeros(3,numel(actual));
for k=1:numel(summary.candidates)
    row=summary.candidates(k);path=fullfile(study,"candidate-complete-Hall-seed-"+row.seed+".mat");
    assert(motorFileSHA256(path)==string(row.checkpoint_sha256));p=load(path,'trainingState','contract');
    assert(p.contract.execution_wrapper_required && ~p.contract.runtime_compatible);
    raw=predict(p.trainingState.actor,dlarray(x,'CB'));
    action=double(extractdata(motorUpper8ActionFromObservation(raw,dlarray(x,'CB'),p.contract)));
    baseline=double(motorUpper8ActionFromObservation(zeros(2,numel(actual)),x,p.contract));
    kp=double(single(.003389))+double(single(.00054224))*action(1,:);
    assert(all(action(2,:)==0) && all(abs(kp-actual)<=.00013556+1e-9));
    [distance,levelIndex]=min(abs(spec.exact_kp_levels(:)-kp),[],1);assert(all(distance<1e-10));
    policies(k,:)=levelIndex;q=zeros(2,numel(actual));b=q;
    nets={p.trainingState.critic1,p.trainingState.critic2};
    for j=1:2
        q(j,:)=predictQ(nets{j},x,single(action));b(j,:)=predictQ(nets{j},x,single(baseline));
    end
    advantage=min(q,[],1)-min(b,[],1);
    value=struct(seed=row.seed,checkpoint_sha256=string(row.checkpoint_sha256), ...
        raw_suggestion_range=row.validation_requested_normalized_Kp_range, ...
        executed_gain_counts=arrayfun(@(j)sum(levelIndex==j),1:3), ...
        executed_distinct_gain_count=numel(unique(levelIndex)), ...
        exact_execution_bounds_and_Ki_passed=true, ...
        mean_predicted_executed_advantage_over_reachable_baseline=mean(advantage), ...
        positive_predicted_advantage_fraction=mean(advantage>0), ...
        mean_executed_twin_disagreement=mean(abs(q(1,:)-q(2,:))), ...
        target_noise_executed_changes=row.target_smoothing_executed_action_changes, ...
        target_action_samples=row.target_action_samples, ...
        actor_policy_is_network_plus_mapping=true,independent_frozen_actor_response_verified=false, ...
        candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
    if isempty(results),results=value;else,results(end+1)=value;end %#ok<AGROW>
end
report=struct(passed=true,results=results,validation_states=numel(actual), ...
    network_plus_map_cross_seed_execution_agreement=mean(all(policies==policies(1,:),1)), ...
    all_policies_constant_after_execution=all([results.executed_distinct_gain_count]==1), ...
    original_recorded_rewards_and_actions_unchanged=true, ...
    target_smoothing_may_be_reduced_by_quantization=true, ...
    method="TD3 plus exact discrete execution and explicit straight-through gradient surrogate", ...
    surrogate_is_not_standard_continuous_TD3=true,hardware_accessed=false,new_physical_windows=0, ...
    actor_applied=false,candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
f=fopen(output,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(report,PrettyPrint=true),'UTF-8'));fclose(f);disp(jsonencode(report));
end
function q=predictQ(net,x,a)
q=double(extractdata(predict(net,dlarray(x,'CB'),dlarray(a,'CB'))));
end
