function report=runMotorUpper8Study(root)
% Fixed whole-boot data study. No physical owner or policy activation.
arguments
    root (1,1) string
end
s=load(fullfile(root,'audited-input.mat'));
assert(s.fullHallAudit.passed && s.fullHallContract.stream_gain_profile=="upper8-fullhall");
assert(s.fullHallAudit.measured_gain_switch_train_windows>=32 && s.fullHallAudit.measured_gain_switch_validation_windows>=32);
contract=struct(action_coordinate_version="absolute-target-upper8-scale0p00054224-v4", ...
    actual_held_kp_levels=double(single([.003389 .00352456 .00366012])), ...
    action_mask=[1 0],Ki_fixed=.00144,actual_action_sampling="balanced-actual-actions", ...
    actor_initialization="range-midpoint",actor_gain_feature="observed", ...
    critic_architecture="local-quadratic",critic_learning_rate=1e-5,critic_weight_decay=.01, ...
    seeds=[7 17 27],reward_modes=["legacy-sparse","complete-Hall"],iterations_per_candidate=600, ...
    source_manifest_sha256=motorFileSHA256(fullfile(root,'replay/summary.json')), ...
    input_sha256=motorFileSHA256(fullfile(root,'audited-input.mat')), ...
    training_boots=s.fullHallContract.training_boot_ids,validation_boots=s.fullHallContract.validation_boot_ids, ...
    midpoint_initialization_avoids_lower_bound_tanh_saturation=true, ...
    physical_performance_verified=false,hardware_accessed=false,actor_applied=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(root,'training-study-contract.json'),contract);studies=struct([]);
for mode=contract.reward_modes
    folder=fullfile(root,"train-"+mode);
    r=trainMotorFullHallTD3(fullfile(root,'audited-input.mat'),fullfile(root,'replay'),folder,600, ...
        Sampling="balanced-actual-actions",RewardModes=mode,Initialization="range-midpoint", ...
        ActorGainFeature="observed",RequireMeasuredSwitches=true,ValueCentering=true, ...
        CriticArchitecture="local-quadratic",CriticWeightDecay=.01,CriticLearningRate=1e-5, ...
        TrainingSeedMode="isolated-update-stream");
    diagnoseMotorFullHallCritics(fullfile(root,'audited-input.mat'),string(folder),fullfile(root,"critic-"+mode+".json"));
    if mode=="complete-Hall"
        auditMotorCrossSeedActions(fullfile(root,'audited-input.mat'),folder,fullfile(root,'cross-seed-complete-Hall.json'));
    end
    row=struct(reward_mode=mode,critic_update_iterations=r.critic_update_iterations,actor_updates=r.actor_updates, ...
        summary_sha256=motorFileSHA256(fullfile(folder,'training-summary.json')));
    if isempty(studies),studies=row;else,studies(end+1)=row;end %#ok<AGROW>
    write(fullfile(root,'training-study-progress.json'),struct(studies=studies));
end
report=struct(passed=true,contract=contract,studies=studies, ...
    critic_update_iterations=sum([studies.critic_update_iterations]),actor_updates=sum([studies.actor_updates]), ...
    hardware_accessed=false,actor_applied=false,candidate_admission=false, ...
    deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(root,'training-study-summary.json'),report);disp(jsonencode(report));
end
function write(path,value)
assert(~isfile(path) || endsWith(path,'progress.json'));
f=fopen(path,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(value,PrettyPrint=true),'UTF-8'));fclose(f);
end
