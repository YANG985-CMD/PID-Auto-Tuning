function report=runMotorInitializationCoordinateStudy(source,output)
% Factorial comparison on one frozen dataset; no real controller writes.
arguments
    source (1,1) string
    output (1,1) string
end
assert(isfolder(output) && ~isfile(fullfile(output,'study-contract.json')));
input=fullfile(source,'audited-input.mat');s=load(input);assert(s.fullHallAudit.passed);
contract=struct(source_input_sha256=motorFileSHA256(input),source_replay_sha256=motorFileSHA256(fullfile(source,'replay/summary.json')), ...
    train_rows=numel(s.fullHallTrain),validation_rows=numel(s.fullHallValidation), ...
    initialization_modes=["random-prior","factual-ridge-bootstrap"], ...
    actor_lambda_coordinates=["native","unshifted-physical"],seeds=[7 17 27],steps_per_candidate=600, ...
    actor_initialization="range-midpoint",actor_gain_feature="observed",reward_mode="complete-Hall", ...
    critic_learning_rate=1e-5,critic_weight_decay=.01,action_mask=[1 0],fixed_ki=.00144, ...
    same_actor_seeds_and_update_rng_streams=true,train_validation_split_unchanged=true, ...
    weak_rank_diagnosis_does_not_claim_motor_unidentifiability=true, ...
    ridge_is_custom_TD3_initialization_not_standard_TD3=true, ...
    hardware_accessed=false,new_physical_windows=0,actor_applied=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(output,'study-contract.json'),contract);studies=struct([]);
for initial=contract.initialization_modes
    for coordinate=contract.actor_lambda_coordinates
        stem=initial+"-"+coordinate;folder=fullfile(output,"train-"+stem);
        r=trainMotorFullHallTD3(input,fullfile(source,'replay'),folder,600, ...
            Sampling="balanced-actual-actions",RewardModes="complete-Hall",Initialization="range-midpoint", ...
            ActorGainFeature="observed",RequireMeasuredSwitches=true,ValueCentering=true, ...
            CriticArchitecture="local-quadratic",CriticWeightDecay=.01,CriticLearningRate=1e-5, ...
            TrainingSeedMode="isolated-update-stream",CriticInitialization=initial,ActorLambdaCoordinates=coordinate);
        diagnoseMotorFullHallCritics(input,string(folder),fullfile(output,"critic-"+stem+".json"));
        auditMotorCrossSeedActions(input,folder,fullfile(output,"cross-seed-"+stem+".json"));
        row=struct(critic_initialization=initial,actor_lambda_coordinate=coordinate, ...
            critic_update_iterations=r.critic_update_iterations,actor_updates=r.actor_updates, ...
            checkpoint_count=numel(r.candidates),source_summary_sha256=motorFileSHA256(fullfile(folder,'training-summary.json')));
        if isempty(studies),studies=row;else,studies(end+1)=row;end %#ok<AGROW>
        write(fullfile(output,'study-progress.json'),struct(studies=studies));
    end
end
original=fullfile(source,'train-complete-Hall');reproduced=fullfile(output,'train-random-prior-native');
error=0;
for seed=contract.seeds
    name="candidate-complete-Hall-seed-"+seed+".mat";
    p=load(fullfile(original,name),'trainingState','candidateReport');q=load(fullfile(reproduced,name),'trainingState','candidateReport');
    for field=["actor","critic1","critic2","targetActor","targetCritic1","targetCritic2"]
        error=max(error,distance(p.trainingState.(field),q.trainingState.(field)));
    end
    assert(isequal(p.trainingState.rng_state,q.trainingState.rng_state));
    assert(isequal(p.candidateReport.minibatch_action_sample_counts,q.candidateReport.minibatch_action_sample_counts));
end
assert(error<1e-8,'MotorTD3:ControlReproduction','Historical arm must reproduce before factorial interpretation');
report=struct(passed=true,contract=contract,studies=studies,historical_arm_reproduction_max_parameter_error=error, ...
    critic_update_iterations=sum([studies.critic_update_iterations]),actor_updates=sum([studies.actor_updates]), ...
    candidate_checkpoints=sum([studies.checkpoint_count]),hardware_accessed=false,new_physical_windows=0, ...
    actor_applied=false,candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(output,'study-summary.json'),report);disp(jsonencode(rmfield(report,'contract')));
end
function d=distance(a,b)
d=0;for k=1:height(a.Learnables),d=max(d,max(abs(double(extractdata(a.Learnables.Value{k}-b.Learnables.Value{k}))),[],'all'));end
end
function write(path,value)
assert(~isfile(path) || endsWith(path,'progress.json'));
f=fopen(path,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(value,PrettyPrint=true),'UTF-8'));fclose(f);
end
