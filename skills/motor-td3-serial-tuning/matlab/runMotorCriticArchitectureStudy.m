function report=runMotorCriticArchitectureStudy(source,output)
% Paired offline TD3 comparison. No hardware access and no deployment approval.
arguments
    source (1,1) string
    output (1,1) string
end
assert(isfolder(output) && startsWith(lower(strrep(output,'\','/')),'e:/simulink/_codex_tmp/'));
assert(jsondecode(fileread(fullfile(output,'quadratic-tests.json'))).passed);
contract=struct(source_dataset="reference-balanced-782-real-windows", ...
    source_manifest_sha256=motorFileSHA256(fullfile(source,'replay/summary.json')), ...
    original_input_sha256=motorFileSHA256(fullfile(source,'audited-input.mat')), ...
    causal_input_sha256=motorFileSHA256(fullfile(source,'causal-input.mat')), ...
    seeds=[7 17 27],critic_iterations_per_candidate=600, ...
    training_seed_mode="isolated-update-stream",update_seed_offset=100000, ...
    variants=["concat-mlp/decay0","local-quadratic/decay0.01"], ...
    local_variant_changes_structure_and_regularization_together=true, ...
    comparison_cannot_separate_structure_from_regularization_effect=true, ...
    physical_rewards_and_boot_split_unchanged=true,actor_architecture_unchanged=true, ...
    fixed_Ki=.00144,action_mask=[1 0],hardware_accessed=false,actor_applied=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
path=fullfile(output,'architecture-study-contract.json');assert(~isfile(path));write(path,contract);
studies=struct([]);
for observation=["original","causal"]
    file="audited-input.mat";if observation=="causal",file="causal-input.mat";end
    for architecture=["concat-mlp","local-quadratic"]
        weight=0;if architecture=="local-quadratic",weight=.01;end
        folder=fullfile(output,"train-"+observation+"-"+architecture);
        r=trainMotorFullHallTD3(fullfile(source,file),fullfile(source,'replay'),folder,600, ...
            Sampling="balanced-actual-actions",RewardModes="complete-Hall",Initialization="near-baseline", ...
            ActorGainFeature="masked",RequireMeasuredSwitches=true,ValueCentering=true, ...
            CriticArchitecture=architecture,CriticWeightDecay=weight,TrainingSeedMode="isolated-update-stream");
        diagnoseMotorFullHallCritics(fullfile(source,file),string(folder), ...
            fullfile(output,"critic-"+observation+"-"+architecture+".json"));
        diagnoseMotorActorGainDependence(fullfile(source,file),folder, ...
            fullfile(output,"gain-dependence-"+observation+"-"+architecture+".json"));
        row=struct(observation=observation,critic_architecture=architecture,critic_decay=weight, ...
            critic_update_iterations=r.critic_update_iterations,actor_updates=r.actor_updates, ...
            training_summary_sha256=motorFileSHA256(fullfile(folder,'training-summary.json')));
        if isempty(studies),studies=row;else,studies(end+1)=row;end %#ok<AGROW>
        write(fullfile(output,'architecture-progress.json'),struct(studies=studies));
    end
end
report=struct(passed=true,contract=contract,studies=studies, ...
    total_critic_update_iterations=sum([studies.critic_update_iterations]), ...
    total_actor_updates=sum([studies.actor_updates]),hardware_accessed=false, ...
    candidate_admission=false,deployment_allowed=false,performance_claim_allowed=false);
write(fullfile(output,'architecture-study-summary.json'),report);
end
function write(path,value)
f=fopen(path,'wb');assert(f>=0);fwrite(f,unicode2native(jsonencode(value,PrettyPrint=true),'UTF-8'));fclose(f);
end
